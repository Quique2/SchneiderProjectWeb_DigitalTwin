const LANG_IDX: Record<ScadaLanguage, number> = { es: 0, en: 1, de: 2, pt: 3, it: 4, fr: 5 };

export function localizeRecommendation(text: string, language: ScadaLanguage): string {
  if (language === 'es') return text;
  const idx = LANG_IDX[language] ?? 1;
  let out = text;
  for (const row of RECOMMENDATION_MAP) {
    out = out.split(row[0]).join(row[idx]);
  }
  return out;
}

export function localizedPillarValue(pillar: string, field: string, value: unknown, language: ScadaLanguage): unknown {
  if (language === 'es') return value;
  if (field === 'estimatedMaintenanceRisk') return riskLabel(value as MaintRisk, language);
  if (field === 'worstComponent') return componentLabel(value as WornComponent, language);
  if (field === 'bottleneckDetected') return bottleneckLabel(value as Bottleneck, language);
  if (typeof value === 'string' && (field.endsWith('Recommendation') || pillar === 'operation')) {
    return localizeRecommendation(value, language);
  }
  return value;
}

