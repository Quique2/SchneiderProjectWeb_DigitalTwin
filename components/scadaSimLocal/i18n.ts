export type ScadaLanguage = 'es' | 'en' | 'de' | 'pt' | 'it' | 'fr';

/** Reads the app-wide language from localStorage (key 'lang', set by LanguageContext). */
export function readStoredScadaLanguage(): ScadaLanguage {
  try {
    const saved = typeof localStorage !== 'undefined' ? localStorage.getItem('lang') : null;
    if (saved === 'es' || saved === 'en' || saved === 'de' || saved === 'pt' || saved === 'it' || saved === 'fr') return saved;
  } catch { /* noop */ }
  return 'es';
}

/** Writes language back to the shared 'lang' key so main app stays in sync. */
export function writeStoredScadaLanguage(language: ScadaLanguage): void {
  try {
    if (typeof localStorage !== 'undefined') localStorage.setItem('lang', language);
  } catch { /* noop */ }
}

