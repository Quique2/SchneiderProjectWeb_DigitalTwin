import { createContext, useContext } from 'react';

export type ScadaLang = 'es' | 'en' | 'de' | 'pt' | 'it' | 'fr';

const VALID_LANGS: ScadaLang[] = ['es', 'en', 'de', 'pt', 'it', 'fr'];

export function readStoredLang(): ScadaLang {
  if (typeof localStorage === 'undefined') return 'es';
  const v = localStorage.getItem('lang');
  return VALID_LANGS.includes(v as ScadaLang) ? (v as ScadaLang) : 'es';
}

export function writeStoredLang(lang: ScadaLang): void {
  if (typeof localStorage !== 'undefined') localStorage.setItem('lang', lang);
}

