export function tsc(lang: ScadaLang, key: string): string {
  return STRINGS[lang]?.[key] ?? STRINGS.es[key] ?? key;
}

// React context — ScadaView provides it; sub-components consume via useScadaT().
export const ScadaLangCtx = createContext<ScadaLang>('es');

export function useScadaT(): (key: string) => string {
  const lang = useContext(ScadaLangCtx);
  return (key: string) => tsc(lang, key);
}

